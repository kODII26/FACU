El grado de precisión es el mayor entero m tal que la fórmula
integra exactamente todos los polinomios de grado ≤ m.

La forma mas simple de probar es con f(x)=[ 1 x x^2 x^3 ...]

Inciso a: Se cumple hasta x^3. Por lo tanto el grado de precision es 3

Inciso b: Tenemos exactitud para 1,x,x^2
